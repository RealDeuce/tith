int
main(void)
{
	static const uint8_t message[] = "profile vector";
	static const uint8_t plaintext[] = "Capabilities\n";
	uint8_t hash[hydro_hash_BYTES];
	uint8_t decrypted[sizeof plaintext - 1];
	uint8_t packet_two[hydro_kx_KK_PACKET2BYTES];
	hydro_hash_state hash_state;
	hydro_kx_session_keypair session_keys;
	int failures = 0;

	if (hydro_init() != 0)
		return 2;
	if (hydro_hash_init(&hash_state, "HashTLV", NULL) != 0 ||
	    hydro_hash_final(&hash_state, NULL, 0) != 0) {
		fprintf(stderr, "zero-length hash finalization failed\n");
		failures++;
	}
	if (hydro_hash_hash(hash, sizeof hash, message, sizeof message - 1,
	    "HashTLV", NULL) != 0 || memcmp(hash, hash_expected, sizeof hash) != 0) {
		fprintf(stderr, "generic hash vector failed\n");
		failures++;
	}
	if (hydro_sign_verify(signature, message, sizeof message - 1,
	    "SignTLV", sign_public) != 0) {
		fprintf(stderr, "signature vector failed\n");
		failures++;
	}
	if (hydro_kx_kk_2(&session_keys, packet_two, kk_packet_one,
	    client_public, &server_keypair) != 0) {
		fprintf(stderr, "KK external packet failed\n");
		failures++;
	}
	if (hydro_secretbox_decrypt(decrypted, secretbox_cipher,
	    sizeof secretbox_cipher, 0, "TITHIPC", secretbox_key) != 0 ||
	    memcmp(decrypted, plaintext, sizeof plaintext - 1) != 0) {
		fprintf(stderr, "secretbox vector failed\n");
		failures++;
	}
	return failures == 0 ? 0 : 1;
}
